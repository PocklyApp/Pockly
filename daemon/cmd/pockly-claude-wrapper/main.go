// readInputs streams /input-stream as long-lived SSE. On any error
// (transport, 404, EOF) it backs off and reconnects so daemon restarts /
// transient hiccups don't permanently sever the web→PTY path. On 404 it
// re-registers so the daemon (which forgot us) gets a fresh entry to
// stream against.
func (b *daemonBridge) readInputs(writePTY func([]byte) (int, error)) {
	backoff := time.Second
	const maxBackoff = 30 * time.Second
	wait := func() bool {
		select {
		case <-b.done:
			return false
		case <-time.After(backoff):
		}
		if backoff < maxBackoff {
			backoff *= 2
			if backoff > maxBackoff {
				backoff = maxBackoff
			}
		}
		return true
	}
	for {
		select {
		case <-b.done:
			return
		default:
		}
		id := b.currentID()
		req, err := http.NewRequest(http.MethodGet, b.base+"/api/dev/terminal-sessions/"+id+"/input-stream", nil)
		if err != nil {
			b.notifyStatus(false)
			if !wait() {
				return
			}
			continue
		}
		resp, err := b.client.Do(req)
		if err != nil {
			b.notifyStatus(false)
			if !wait() {
				return
			}
			continue
		}
		if resp.StatusCode == http.StatusNotFound {
			resp.Body.Close()
			b.notifyStatus(false)
			if rerr := b.reregister(); rerr != nil {
				if !wait() {
					return
				}
				continue
			}
			b.notifyStatus(true)
			backoff = time.Second
			continue
		}
		if resp.StatusCode < 200 || resp.StatusCode >= 300 {
			resp.Body.Close()
			b.notifyStatus(false)
			if !wait() {
				return
			}
			continue
		}
		// Connected. Reset backoff and stream until error/EOF.
		b.notifyStatus(true)
		backoff = time.Second
		scanner := bufio.NewScanner(resp.Body)
		for scanner.Scan() {
			select {
			case <-b.done:
				resp.Body.Close()
				return
			default:
			}
			line := scanner.Text()
			if !strings.HasPrefix(line, "data: ") {
				continue
			}
			var payload struct {
				Text string `json:"text"`
			}
			if err := json.Unmarshal([]byte(strings.TrimPrefix(line, "data: ")), &payload); err == nil && payload.Text != "" {
				writeRemoteInput(writePTY, payload.Text)
			}
		}
		resp.Body.Close()
		// Stream ended (daemon closed, EOF, scanner err). Mark detached so
		// the indicator goes yellow; loop will reconnect.
		b.notifyStatus(false)
		if !wait() {
			return
		}
	}
}

func (b *daemonBridge) rememberMessageEvent(event jsonlMessageEvent) bool {
	if strings.TrimSpace(event.UUID) == "" {
		return true
	}
	key := event.UUID + "|" + event.Role + "|" + strconv.Itoa(event.Segment) + "|" + event.ID
	b.emittedMu.Lock()
	defer b.emittedMu.Unlock()
	if b.emittedMessageKeys == nil {
		b.emittedMessageKeys = map[string]struct{}{}
	}
	if _, ok := b.emittedMessageKeys[key]; ok {
		return false
	}
	b.emittedMessageKeys[key] = struct{}{}
	return true
}

// Prompt-ready detector state, shared between run()'s idle ticker and the
// two input paths (local stdin loop + remote inject via writeRemoteInput).
// promptReadyArmed is set only when a slash command is submitted; the
// ticker then emits a single prompt_ready once PTY output settles.
var (
	promptReadyArmed  atomic.Bool
	lastPTYOutputNano atomic.Int64
)

// slashCommandRE matches a single "/name" token: one leading slash, a
// lowercase-letter start, then letters/digits/[-:_]. This recognizes real
// Claude slash commands ("/model", "/clear", "/pr-comments") while
// rejecting file paths a user might send as a message ("/Users/x",
// "/usr/bin" — embedded slashes or an uppercase start fail the match).
var slashCommandRE = regexp.MustCompile(`^/[a-z][a-z0-9:_-]*$`)

func looksLikeSlashCommand(text string) bool {
	t := strings.TrimSpace(text)
	if !strings.HasPrefix(t, "/") {
		return false
	}
	first := t
	if i := strings.IndexAny(t, " \t"); i >= 0 {
		first = t[:i]
	}
	return slashCommandRE.MatchString(first)
}

func advanceANSIInputState(state int, b byte) int {
	switch state {
	case 1:
		switch b {
		case '[':
			return 2
		case 'O':
			return 3
		default:
			return 0
		}
	case 2:
		if b >= 0x40 && b <= 0x7e {
			return 0
		}
		return 2
	case 3:
		return 0
	default:
		return 0
	}
}

type modelSwitchConfirmer struct {
	write       func([]byte) (int, error)
	pendingTail []byte
	buffer      string
	lastConfirm time.Time
}

func newModelSwitchConfirmer(write func([]byte) (int, error)) *modelSwitchConfirmer {
	if write == nil {
		return &modelSwitchConfirmer{}
	}
	return &modelSwitchConfirmer{write: write}
}

func (c *modelSwitchConfirmer) Feed(chunk []byte) {
	if c == nil || c.write == nil || len(chunk) == 0 {
		return
	}
	clean, tail := stripANSIChunk(c.pendingTail, chunk)
	c.pendingTail = tail
	if clean == "" {
		return
	}
	c.buffer += clean
	if len(c.buffer) > 4096 {
		c.buffer = c.buffer[len(c.buffer)-4096:]
	}
	if !detectModelSwitchPrompt(c.buffer) {
		return
	}
	now := time.Now()
	if now.Sub(c.lastConfirm) < 3*time.Second {
		return
	}
	c.lastConfirm = now
	c.buffer = ""
	go func() {
		time.Sleep(120 * time.Millisecond)
		_, _ = c.write([]byte("\r"))
	}()
}

func detectModelSwitchPrompt(screen string) bool {
	s := strings.ToLower(screen)
	return strings.Contains(s, "switch model?") &&
		strings.Contains(s, "yes, switch") &&
		strings.Contains(s, "no, go back")
}

func armPromptReady() {
	promptReadyArmed.Store(true)
	lastPTYOutputNano.Store(time.Now().UnixNano())
}

func writeRemoteInput(writePTY func([]byte) (int, error), text string) {
	// A remotely-injected slash command (e.g. the web model pill's
	// "/model X") produces no assistant turn, so arm the prompt-ready
	// detector to return turn_status to awaiting_input once it settles.
	// Normal injected prompts are left alone — their assistant reply ends
	// the run on the web side.
	if looksLikeSlashCommand(text) {
		armPromptReady()
	}
	if runtime.GOOS == "windows" {
		switch {
		case strings.HasSuffix(text, "\r\n") && len(text) > 2:
			_, _ = writePTY([]byte(strings.TrimSuffix(text, "\r\n")))
			time.Sleep(250 * time.Millisecond)
			_, _ = writePTY([]byte("\r"))
			return
		case strings.HasSuffix(text, "\r") && len(text) > 1:
			_, _ = writePTY([]byte(strings.TrimSuffix(text, "\r")))
			time.Sleep(250 * time.Millisecond)
			_, _ = writePTY([]byte("\r"))
			return
		}
	}
	_, _ = writePTY([]byte(text))
}

func setEnv(env []string, key, value string) []string {
	prefix := key + "="
	out := make([]string, 0, len(env)+1)
	replaced := false
	for _, item := range env {
		if strings.HasPrefix(item, prefix) {
			out = append(out, prefix+value)
			replaced = true
		} else {
			out = append(out, item)
		}
	}
	if !replaced {
		out = append(out, prefix+value)
	}
	return out
}

func defaultString(v, fallback string) string {
	if strings.TrimSpace(v) == "" {
		return fallback
	}
	return v
}

func samePath(a, b string) bool {
	if a == "" || b == "" {
		return false
	}
	ar, aerr := os.Stat(a)
	br, berr := os.Stat(b)
	return aerr == nil && berr == nil && os.SameFile(ar, br)
}

// parseClaudeInvocation walks the user's argv and extracts whatever
// session-binding intent it can find. It does NOT mutate the args. The
// caller (resolveLockedSessionID) decides what to do with the result —
// including generating a fresh UUID + injecting --session-id when the
// user passed nothing.
//
// The flags we care about (all from `claude --help`):
//
//	--session-id <uuid>    Use a specific session ID. Authoritative.
//	--resume / -r <sid>    Resume a specific session. Authoritative.
//	--continue / -c        Resume the most recent session in cwd. The
//	                       wrapper *can* pre-resolve this by reading the
//	                       project dir, but the parse step only flags it.
//	--fork-session         When resuming, claude generates a new UUID.
//	                       We can't know it in advance; lockable=false.
func parseClaudeInvocation(args []string) claudeInvocation {
	var out claudeInvocation
	hasResume := false
	hasContinue := false
	hasFork := false
	hasSessionIDFlag := false
	for i := 0; i < len(args); i++ {
		arg := strings.TrimSpace(args[i])
		switch {
		case arg == "--session-id" && i+1 < len(args):
			out.sessionID = strings.TrimSpace(args[i+1])
			hasSessionIDFlag = true
			i++
		case strings.HasPrefix(arg, "--session-id="):
			out.sessionID = strings.TrimSpace(strings.TrimPrefix(arg, "--session-id="))
			hasSessionIDFlag = true
		case arg == "--resume" && i+1 < len(args) && !strings.HasPrefix(args[i+1], "-"):
			// Be careful: --resume's value is optional (opens a picker
			// when absent). If next arg starts with `-` we treat it as
			// "no value" and the picker path applies — claude generates
			// a new sid after the user picks, which we can't know.
			out.sessionID = strings.TrimSpace(args[i+1])
			hasResume = true
			i++
		case arg == "--resume":
			hasResume = true // value-less picker form
		case strings.HasPrefix(arg, "--resume="):
			out.sessionID = strings.TrimSpace(strings.TrimPrefix(arg, "--resume="))
			hasResume = true
		case arg == "-r" && i+1 < len(args) && !strings.HasPrefix(args[i+1], "-"):
			out.sessionID = strings.TrimSpace(args[i+1])
			hasResume = true
			i++
		case arg == "-r":
			hasResume = true
		case arg == "--continue" || arg == "-c":
			hasContinue = true
		case arg == "--fork-session":
			hasFork = true
		}
	}
	// --fork-session always creates a new sid, regardless of what
	// --resume said. We genuinely don't know it in advance.
	if hasFork {
		out.sessionID = ""
		out.lockable = false
		out.injectFlag = false
		return out
	}
	// User passed --session-id directly: pass-through, no injection.
	if hasSessionIDFlag && out.sessionID != "" {
		out.lockable = true
		out.injectFlag = false
		return out
	}
	// User passed --resume with an explicit sid: lockable, no injection
	// (the --resume already binds claude to that sid).
	if hasResume && out.sessionID != "" {
		out.lockable = true
		out.injectFlag = false
		return out
	}
	// --resume picker (value-less) or --continue: caller needs to
	// pre-resolve to a sid by inspecting the project dir, then we'll
	// rewrite the args to `--resume <sid>` in resolveLockedSessionID.
	// Mark not-yet-lockable and let the resolver fill it in.
	if hasResume || hasContinue {
		out.sessionID = ""
		out.lockable = false
		out.injectFlag = false
		return out
	}
	// Bare `claude` (or any args that aren't session-related): wrapper
	// generates the UUID and will inject --session-id when launching.
	out.sessionID = newUUIDv4()
	out.lockable = true
	out.injectFlag = true
	return out
}

// resolveLockedSessionID finalizes the wrapper's binding decision and
// returns the final argv to exec with. It handles the two cases that
// parseClaudeInvocation couldn't fully resolve on its own:
//
//   - --continue / value-less --resume → scan projectDir, find the
//     most-recently-modified CLI-owned jsonl, extract its sid, rewrite
//     the args to `--resume <sid>` so claude can't surprise us with a
//     different pick.
//   - bare `claude` (injectFlag=true) → prepend the generated sid as
//     --session-id <uuid>.
//
// Returns the rewritten args + the final claudeInvocation (with sid
// + lockable filled in). If pre-resolution fails (e.g. --continue in
// an empty project dir, where there's nothing to continue), we return
// the original invocation with lockable=false — the wrapper will fall
// through to the legacy fd-discovery path and log a warning.
func resolveLockedSessionID(args []string, projectDir string) ([]string, claudeInvocation) {
	inv := parseClaudeInvocation(args)
	if inv.lockable && inv.injectFlag {
		// Bare invocation, wrapper-generated sid. Prepend the flag.
		out := make([]string, 0, len(args)+2)
		out = append(out, "--session-id", inv.sessionID)
		out = append(out, args...)
		inv.injectFlag = false // consumed
		return out, inv
	}
	if !inv.lockable && inv.sessionID == "" {
		// Two sub-cases reach here: --continue / value-less --resume
		// (which we can pre-resolve from projectDir), or --fork-session
		// (which we can't). Distinguish by re-scanning the args; if
		// --fork-session is in there, give up.
		if containsFlag(args, "--fork-session") {
			return args, inv // truly non-lockable, fall back to fd discovery
		}
		// Try to pre-resolve: scan projectDir for the newest CLI jsonl
		// that existed BEFORE the wrapper started (we don't know
		// childStartedAt at this point; use time.Time{} so any mtime
		// counts — we just want "what would --continue have picked").
		if sid, _, ok := newestJSONLAfter(projectDir, time.Time{}); ok {
			// Rewrite the args: strip --continue / -c / --resume, add
			// --resume <sid>. This way claude can't deviate from the
			// session we just inspected (if the user starts another
			// claude in the same dir between our scan and exec, --resume
			// is now pinned to the sid we picked).
			rewritten := stripFlags(args, []string{"--continue", "-c", "--resume", "-r"})
			rewritten = append(rewritten, "--resume", sid)
			inv.sessionID = sid
			inv.lockable = true
			return rewritten, inv
		}
		// Empty project dir, nothing to continue. Fall through; claude
		// will likely error out itself.
		return args, inv
	}
	// inv.lockable && !inv.injectFlag: user provided --resume <sid> or
	// --session-id <x>; we already know the sid and nothing needs
	// rewriting.
	return args, inv
}

// newUUIDv4 returns a fresh random UUID in canonical 8-4-4-4-12 form.
// Used to pre-bind `claude --session-id <uuid>` before exec, so the
// wrapper knows the jsonl path without any after-the-fact discovery.
//
// We hand-roll instead of pulling in github.com/google/uuid because the
// daemon's dep graph is intentionally lean (see go.mod) and the
// RFC 4122 v4 layout is 6 lines of code. The fallback branch covers
// the theoretically-impossible "crypto/rand fails" case so the wrapper
// never blocks a claude launch on entropy starvation.
func newUUIDv4() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		ts := time.Now().UnixNano()
		return fmt.Sprintf("%08x-%04x-4%03x-%04x-%012x",
			uint32(ts), uint16(ts>>32), uint16(ts>>16)&0xfff,
			uint16(0x8000)|uint16(ts&0x3fff), ts)
	}
	// Set version (4) and variant (10xx) bits per RFC 4122.
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	// fmt's %x on a byte slice prints lowercase hex, 2 chars per byte —
	// exactly the UUID canonical encoding.
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// containsFlag returns true if any arg matches name (exact match or
// `name=value` form). Used to spot --fork-session without re-parsing.
func containsFlag(args []string, name string) bool {
	prefix := name + "="
	for _, a := range args {
		if a == name || strings.HasPrefix(a, prefix) {
			return true
		}
	}
	return false
}

// stripFlags returns args with the named flags removed, taking values
// when present. e.g. stripFlags(["--resume","abc","-v"], ["--resume"])
// → ["-v"]. Used when rewriting `--continue` to `--resume <pre-resolved-sid>`.
func stripFlags(args []string, names []string) []string {
	skip := map[string]bool{}
	for _, n := range names {
		skip[n] = true
	}
	out := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		a := args[i]
		// Exact match: consume value if next arg doesn't start with `-`.
		if skip[a] {
			if i+1 < len(args) && !strings.HasPrefix(args[i+1], "-") {
				i++ // drop the value too
			}
			continue
		}
		// `--name=value` form.
		dropped := false
		for n := range skip {
			if strings.HasPrefix(a, n+"=") {
				dropped = true
				break
			}
		}
		if dropped {
			continue
		}
		out = append(out, a)
	}
	return out
}

// --- Bottom-right "Pockly attached" status indicator ---
//
// We paint ANSI escape sequences directly to the user's terminal to show a
// small cyan badge in the bottom-right corner. The wrapper does not own the
// screen — Claude (Ink/React) drives most of it — so the indicator gets
// overwritten as Claude redraws. We re-paint right after each PTY output
// chunk (throttled to ~5 fps) so the indicator naturally tracks Claude's
// own paint cadence without polling.
//
// Cursor save/restore uses DECSC (\x1b7) / DECRC (\x1b8). Ink-based TUIs
// drive the cursor via CUP rather than these registers, so clobbering the
// save slot is observed-safe in practice.

const (
	statusIndicatorColorAttached = "\x1b[36m" // cyan
	statusIndicatorColorDetached = "\x1b[33m" // yellow
	statusIndicatorResetSeq      = "\x1b[0m"
	statusIndicatorMinInterval   = 200 * time.Millisecond
)

// statusIndicatorTextAttached / Detached include the wrapper's version
// suffix ("Pockly v0.1.29 attached" / "Pockly v0.1.29 reconnecting") so
// users can see at a glance which daemon version is running without
// shelling out to `pockly-daemon --version` — especially useful after a
// `pockly-daemon update` to confirm the new bits took. We embed the
// version in the state text (not a separate badge) so the bottom-right
// reservation block stays a single rectangle the cursor logic can
// rewind over cleanly.
func statusIndicatorTextAttached() string {
	return "Pockly v" + version.Version + " attached"
}

func statusIndicatorTextDetached() string {
	return "Pockly v" + version.Version + " reconnecting"
}

// statusIndicatorWidth is the column count to reserve / erase. Use the
// wider of the two states so a transition between them never leaves
// stale characters.
func statusIndicatorWidth() int {
	a := statusIndicatorTextAttached()
	d := statusIndicatorTextDetached()
	if len(d) > len(a) {
		return len(d)
	}
	return len(a)
}

type statusIndicator struct {
	out         *os.File
	write       func([]byte) (int, error)
	mu          sync.Mutex
	lastPaintAt time.Time
	paintToken  uint64
	closeOnce   sync.Once
	closed      bool
	attached    bool // true → green/cyan attached, false → yellow reconnecting
}

func newStatusIndicator(out *os.File, write func([]byte) (int, error), initialAttached bool) *statusIndicator {
	return &statusIndicator{out: out, write: write, attached: initialAttached}
}

// SetAttached flips the indicator's state. Repaints immediately on a
// state change so the user gets timely feedback when daemon drops or
// recovers; same-state calls are no-ops.
func (s *statusIndicator) SetAttached(attached bool) {
	s.mu.Lock()
	if s.closed || s.attached == attached {
		s.mu.Unlock()
		return
	}
	s.attached = attached
	s.paintLocked()
	s.mu.Unlock()
}

// maybePaint paints the indicator if the rate limit allows. Cheap to call.
func (s *statusIndicator) maybePaint() {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed || time.Since(s.lastPaintAt) < statusIndicatorMinInterval {
		return
	}
	s.paintLocked()
}

// paintNow paints unconditionally (used on startup and resize).
func (s *statusIndicator) paintNow() {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return
	}
	s.paintLocked()
}

func (s *statusIndicator) schedulePaint(delay time.Duration) {
	token := atomic.AddUint64(&s.paintToken, 1)
	go func() {
		time.Sleep(delay)
		if atomic.LoadUint64(&s.paintToken) != token {
			return
		}
		s.paintNow()
	}()
}

func (s *statusIndicator) paintLocked() {
	if !term.IsTerminal(int(s.out.Fd())) {
		return
	}
	width := statusIndicatorWidth()
	cols, rows, err := term.GetSize(int(s.out.Fd()))
	if err != nil || cols < width+2 || rows < 2 {
		return
	}
	text := statusIndicatorTextAttached()
	color := statusIndicatorColorAttached
	if !s.attached {
		text = statusIndicatorTextDetached()
		color = statusIndicatorColorDetached
	}
	// Right-align within a column block sized to the wider of the two states,
	// so transitions don't leave stale trailing characters behind.
	pad := strings.Repeat(" ", width-len(text))
	col := cols - width
	// One-indexed cursor positioning. Stay one cell shy of the last column
	// to avoid implementation-specific auto-wrap behavior in the corner.
	seq := fmt.Sprintf("\x1b7\x1b[%d;%dH%s%s%s%s\x1b8",
		rows, col, color, text, statusIndicatorResetSeq, pad)
	_, _ = s.write([]byte(seq))
	s.lastPaintAt = time.Now()
}

func (s *statusIndicator) erase() {
	s.mu.Lock()
	defer s.mu.Unlock()
	if !term.IsTerminal(int(s.out.Fd())) {
		return
	}
	width := statusIndicatorWidth()
	cols, rows, err := term.GetSize(int(s.out.Fd()))
	if err != nil || cols < width+2 || rows < 2 {
		return
	}
	col := cols - width
	blank := strings.Repeat(" ", width)
	seq := fmt.Sprintf("\x1b7\x1b[%d;%dH%s\x1b8", rows, col, blank)
	_, _ = s.write([]byte(seq))
}

func (s *statusIndicator) close() {
	s.closeOnce.Do(func() {
		s.erase()
		s.mu.Lock()
		s.closed = true
		s.mu.Unlock()
	})
}
