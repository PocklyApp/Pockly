func (b *daemonBridge) registerPermissionRequest(reqID, toolName string, input json.RawMessage) error {
	body, _ := json.Marshal(map[string]any{
		"terminal_session_id": b.currentID(),
		"claude_session_id":   b.ClaudeSessionID(),
		"tool_name":           toolName,
		"input":               rawJSONOrObject(input),
	})
	req, err := http.NewRequest(http.MethodPost, b.base+"/api/dev/permission-requests/"+reqID, bytes.NewReader(body))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	resp, err := b.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 300 {
		buf, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("daemon %d: %s", resp.StatusCode, truncateBridgeLog(string(buf), 160))
	}
	return nil
}

func (b *daemonBridge) awaitPermissionDecision(reqID string, timeout time.Duration) (permissionAwaitOutcome, error) {
	timeoutSec := int(timeout / time.Second)
	if timeoutSec <= 0 {
		timeoutSec = 30
	}
	req, err := http.NewRequest(http.MethodGet, fmt.Sprintf("%s/api/dev/permission-requests/%s/await?timeout=%d", b.base, reqID, timeoutSec), nil)
	if err != nil {
		return permissionAwaitOutcome{}, err
	}
	resp, err := b.client.Do(req)
	if err != nil {
		return permissionAwaitOutcome{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		buf, _ := io.ReadAll(resp.Body)
		return permissionAwaitOutcome{}, fmt.Errorf("daemon %d: %s", resp.StatusCode, truncateBridgeLog(string(buf), 160))
	}
	var out permissionAwaitOutcome
	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		return permissionAwaitOutcome{}, err
	}
	return out, nil
}

