func (w *tuiPermissionWatcher) handle(prompt tuiPermissionPrompt) {
	defer w.finish(prompt)
	input, _ := json.Marshal(prompt.Input)
	if prompt.LocalOnly {
		w.bridge.emitPermissionEvent(prompt.ToolName, input, "", "local_confirmation", "Claude is waiting for confirmation in the local terminal")
		return
	}
	reqID := "req-pty-" + strings.ReplaceAll(newUUIDv4(), "-", "")
	if err := w.bridge.registerPermissionRequest(reqID, prompt.ToolName, input); err != nil {
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] PTY permission register failed: %v\n", err)
		return
	}
	w.bridge.emitPermissionEvent(prompt.ToolName, input, reqID, "pending", "v0.2.x awaiting web approval (PTY)")
	out, err := w.bridge.awaitPermissionDecision(reqID, w.timeout)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] PTY permission await failed: %v\n", err)
		return
	}
	if out.Reason == "timeout" {
		w.bridge.emitPermissionEvent(prompt.ToolName, input, reqID, out.Decision, "v0.2.x web decision timed out (PTY)")
		return
	}
	key := webPermissionKey(out.Decision, w.bridge.claudeSessionWaitingForPermission(), prompt.AllowKey, prompt.DenyKey)
	if key == "" {
		// Either the decision has no native keystroke, or Claude already advanced
		// past the prompt because the user answered it at the local terminal while
		// we were parked on the web decision. Writing the key now would inject a
		// stray keystroke into Claude's stdin, so drop it — the local answer
		// already resolved the prompt.
		w.bridge.emitPermissionEvent(prompt.ToolName, input, reqID, out.Decision, "v0.2.x web decision dropped — claude no longer waiting (PTY)")
		return
	}
	_, _ = w.write([]byte(key))
	w.bridge.emitPermissionEvent(prompt.ToolName, input, reqID, out.Decision, "v0.2.x web decision applied (PTY)")
}

// tuiDecisionKey maps a web decision to the PTY keystroke that selects the
// matching option, using the option numbers parsed from THIS prompt (allowKey
// = one-time Yes, denyKey = No). Falls back to Claude's historical 1 (one-time
// Yes — never 2, which persists an "always allow" rule) / 3 (No) when the
// numbers weren't parsed.
func tuiDecisionKey(decision, allowKey, denyKey string) string {
	if allowKey == "" {
		allowKey = "1"
	}
	if denyKey == "" {
		denyKey = "3"
	}
	switch strings.TrimSpace(strings.ToLower(decision)) {
	case "allow":
		return allowKey + "\r"
	case "deny":
		return denyKey + "\r"
	default:
		return ""
	}
}

func tuiPermissionDecisionKey(decision string) string {
	return tuiDecisionKey(decision, "", "")
}

// webPermissionKeyToWrite returns the PTY keystroke that forwards a web
// permission decision into Claude's TUI, or "" when nothing should be written.
//
// It returns "" when stillWaiting is false: that means the user already answered
// this prompt at the local terminal while we were parked awaiting the web
// decision, so Claude has advanced past the prompt and is no longer blocked.
// Writing the decision key in that window would inject a stray "1"/"3" keystroke
// into Claude's stdin — corrupting the next prompt or triggering an unintended
// selection (the "double-decide" bug). It also returns "" for decisions with no
// native keystroke. Forward the decision only when Claude is genuinely still
// waiting AND the decision maps to a key.
func webPermissionKeyToWrite(decision string, stillWaiting bool) string {
	return webPermissionKey(decision, stillWaiting, "", "")
}

// webPermissionKey is webPermissionKeyToWrite with the prompt's parsed option
// numbers (B7). Same "don't write a stray key once Claude has advanced" guard.
func webPermissionKey(decision string, stillWaiting bool, allowKey, denyKey string) string {
	if !stillWaiting {
		return ""
	}
	return tuiDecisionKey(decision, allowKey, denyKey)
}

