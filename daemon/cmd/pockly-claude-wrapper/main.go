// claudeInvocation summarizes what the user asked of claude. The wrapper
// uses this to decide whether it can safely lock onto a session ID
// *before* exec'ing claude (the v0.1.36 anchor) — or whether claude will
// be free to pick its own and we have to fall back to fd-based discovery
// after the fact.
type claudeInvocation struct {
	// sessionID is the UUID we will guarantee claude binds to. It is
	// either parsed from --resume / --session-id, pre-resolved from
	// --continue, or generated by the wrapper. Empty only when the user
	// passed --fork-session (claude generates a fresh one — we can't
	// know it in advance).
	sessionID string
	// lockable is true when sessionID was determined before exec. The
	// wrapper guarantees a `<sessionID>.jsonl` path and never has to
	// discover anything. False = --fork-session, fall back to the old
	// fd-discovery + watchActiveSessionID path.
	lockable bool
	// injectFlag is true when the wrapper needs to prepend
	// `--session-id <sessionID>` to the args itself. False when the
	// user already supplied --session-id (don't double-pass) or the
	// case is --fork-session (no session id to inject).
	injectFlag bool
}

func main() {
	log.SetFlags(0)
	cfg := parseArgs()
	if err := run(cfg); err != nil {
		log.Fatal(err)
	}
}

func parseArgs() config {
	fs := flag.NewFlagSet("pockly-claude-wrapper", flag.ExitOnError)
	cwd := fs.String("cwd", "", "working directory for Claude; default current directory")
	alt := fs.Bool("alt-screen", false, "run inside terminal alternate screen; disables normal terminal scrollback")
	noRaw := fs.Bool("no-raw", false, "do not put this terminal in raw mode")
	clear := fs.Bool("clear", true, "clear visible screen before drawing Claude")
	debug := fs.Bool("debug", false, "print wrapper diagnostics to stderr")
	attachLatest := fs.Bool("attach-latest", false, "attach to the newest Pockly-managed live Claude PTY instead of launching Claude")
	daemonURL := fs.String("daemon-url", defaultDaemonURL(), "local pockly-daemon URL used with --attach-latest or external registration")
	register := fs.Bool("register", true, "register this transparent Claude PTY with local pockly-daemon")
	real := fs.String("real", "", "real Claude executable path; default PATH lookup")
	pass := fs.Bool("pass", false, "force direct exec without PTY wrapping")
	noIndicator := fs.Bool("no-indicator", false, "hide the bottom-right \"Pockly attached\" status indicator")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, `Usage:
  pockly-claude-wrapper [wrapper flags] -- [claude args...]

Examples:
  pockly-claude-wrapper
  pockly-claude-wrapper -- --resume <session-id>
  pockly-claude-wrapper --alt-screen -- --resume <session-id>

Wrapper flags:
`)
		fs.PrintDefaults()
	}
	_ = fs.Parse(os.Args[1:])
	return config{cwd: *cwd, altScreen: *alt, rawMode: !*noRaw, clear: *clear, debug: *debug, pass: *pass, attachLatest: *attachLatest, daemonURL: *daemonURL, register: *register, real: *real, noIndicator: *noIndicator, args: fs.Args()}
}

func defaultDaemonURL() string {
	if value := strings.TrimSpace(os.Getenv("POCKLY_DAEMON_URL")); value != "" {
		return strings.TrimRight(value, "/")
	}
	return "http://127.0.0.1:8947"
}

func run(cfg config) error {
	if cfg.attachLatest || os.Getenv("POCKLY_CLAUDE_ATTACH_LATEST") == "1" {
		return attachLatestPocklyTerminal(cfg)
	}
	self, _ := os.Executable()
	claudeCmd, err := claudelauncher.Resolve(cfg.real, self)
	if err != nil {
		return err
	}
	envSnap := wrapperEnvSnapshot()
	cwd := cfg.cwd
	if strings.TrimSpace(cwd) == "" {
		cwd, err = os.Getwd()
		if err != nil {
			return err
		}
	}

	if cfg.pass || shouldPassThrough(cfg.args) || !term.IsTerminal(int(os.Stdin.Fd())) || !term.IsTerminal(int(os.Stdout.Fd())) {
		return execDirect(claudeCmd, cwd, cfg.args, envSnap.Env)
	}

	// v0.1.36: lock the session id BEFORE exec'ing claude. resolveLockedSessionID
	// either generates a fresh UUID and prepends `--session-id <uuid>` (bare
	// `claude`), pre-resolves --continue / value-less --resume to a specific
	// sid + rewrites to `--resume <sid>`, or passes through unchanged when the
	// user already supplied --session-id / --resume <sid>. Only --fork-session
	// hits the legacy fd-discovery path (claude generates a sid we can't know).
	//
	// Why pre-bind: with two claude terminals in the same cwd, the wrapper's
	// post-hoc discovery used to flip-flop between their jsonls when fd-based
	// discovery failed (containers, lsof missing) and we fell back to mtime
	// newest. Anchoring on a wrapper-generated UUID makes the binding
	// authoritative — fileSystem name = UUID, jsonl content sessionId field =
	// UUID, OS fd table (when available) = UUID.
	finalArgs, invocation := resolveLockedSessionID(cfg.args, claudeProjectDir(cwd))
	// v0.1.42: inject MCP permission server so the "Do you want to
	// proceed?" prompt becomes a structured event the web tab can see
	// (instead of a TUI 1/2 dialog only visible at the terminal). The
	// server (`pockly-daemon mcp-permission`) auto-approves everything
	// in v0.1.42 (read-only observability); v0.2.0 will block on a
	// web decision. Cleanup of the temp mcp-config file happens via
	// defer below. Skipped silently if we can't find the daemon
	// binary — the wrapper still works without the permission relay.
	mcpConfigPath, mcpCleanup, mcpArgs := setupPermissionMCP(invocation.sessionID)
	if mcpCleanup != nil {
		defer mcpCleanup()
	}
	if len(mcpArgs) > 0 {
		finalArgs = append(finalArgs, mcpArgs...)
		if cfg.debug {
			fmt.Fprintf(os.Stderr, "[pockly wrapper] permission MCP enabled via %s\n", mcpConfigPath)
		}
	}
	// v0.3.0 H2: install a PreToolUse hook entry into the user's
	// ~/.claude/settings.json so claude routes built-in tools
	// (Bash/Read/Write/Edit/Skill) through `pockly-daemon hook-bridge`.
	// MCP path (above) only catches MCP-namespaced tools; this catches
	// the rest. Cleanup defer removes our entries on wrapper exit
	// even if claude crashed. Self-heals if a prior wrapper crashed
	// without cleanup. Disabled when POCKLY_DISABLE_PERMISSION_HOOK=1.
	hookCleanup, hookErr := setupHookBridge(resolvePocklyDaemonPath())
	if hookErr != nil && cfg.debug {
		fmt.Fprintf(os.Stderr, "[pockly wrapper] hook bridge setup: %v (auto-mode disabled for built-in tools)\n", hookErr)
	} else if hookErr == nil && cfg.debug {
		fmt.Fprintf(os.Stderr, "[pockly wrapper] hook bridge installed in claude settings.json (v0.3.0 auto-mode)\n")
	}
	if hookCleanup != nil {
		defer hookCleanup()
	}
	// childStartedAt is captured RIGHT BEFORE startPTY launches the
	// claude child. discoverSessionIDFromProjectsDir uses it as the mtime
	// cutoff for "this jsonl belongs to the claude we just spawned." If we
	// captured time.Now() inside the goroutine instead, fast-write claudes
	// (fake-claude, claude --print) could finish writing their first event
	// before the goroutine even runs — making their mtime < startedAt and
	// the rule `mtime >= startedAt` miss every time. That symptom (relay
	// stuck at read_only_sync forever) is what this earlier-capture fixes.
	size := currentSize()
	childStartedAt := time.Now()
	ptmx, err := startPTY(claudeCmd, finalArgs, cwd, envSnap.Env, size)
	if err != nil {
		// v0.4.0 W1: on Windows, ConPTY can fail for reasons that are
		// outside our control (older Windows 10 < 1809, certain
		// embedded SKUs, ConHost compatibility flags). When that
		// happens, fall back to a plain execDirect so the user can
		// still run claude and the daemon's session sync still
		// works — only the live PTY mirror + auto-mode hook bridge
		// degrade. On other platforms, PTY failure is exceptional
		// enough to surface to the caller.
		if runtime.GOOS == "windows" {
			fmt.Fprintf(os.Stderr, "[pockly wrapper] PTY (ConPTY) failed on Windows: %v\n", err)
			fmt.Fprintln(os.Stderr, "[pockly wrapper] falling back to direct exec — session sync still works, but no live PTY mirror or auto-mode permission cards")
			return execDirect(claudeCmd, cwd, cfg.args, envSnap.Env)
		}
		return err
	}
	defer ptmx.Close()

	if cfg.debug {
		fmt.Fprintf(os.Stderr, "[pockly wrapper] claude_launcher_source=%s path=%s prefix_args=%d cwd=%s size=%dx%d alt=%v raw=%v args=%q settings_env_keys=%q settings_env_error=%q\n", claudeCmd.Source, claudeCmd.Path, claudeCmd.LauncherArgCount(), cwd, size.Cols, size.Rows, cfg.altScreen, cfg.rawMode, cfg.args, envSnap.SettingsEnvKeys, envSnap.SettingsEnvError)
	}

	restoreScreen := setupScreen(cfg)
	defer restoreScreen()

	restoreTerm, err := setupTerminal(cfg)
	if err != nil {
		return err
	}
	defer restoreTerm()

	done := make(chan error, 2)
	var writeMu sync.Mutex
	writePTY := func(p []byte) (int, error) {
		writeMu.Lock()
		defer writeMu.Unlock()
		return ptmx.Write(p)
	}
	var stdoutMu sync.Mutex
	writeStdout := func(p []byte) (int, error) {
		stdoutMu.Lock()
		defer stdoutMu.Unlock()
		return os.Stdout.Write(p)
	}
	// invocation was already computed by resolveLockedSessionID before exec —
	// it carries the locked sessionID (or empty for --fork-session) so the
	// daemon bridge can pre-register the right binding instead of waiting for
	// post-hoc discovery to converge.
	bridge, bridgeErr := maybeStartDaemonBridge(cfg, cwd, invocation, writePTY, childStartedAt, ptmx.Pid())
	if bridgeErr != nil && cfg.debug {
		fmt.Fprintf(os.Stderr, "[pockly wrapper] daemon bridge disabled: %v\n", bridgeErr)
	}

	var indicator *statusIndicator
	if !cfg.noIndicator {
		// Initial badge color reflects whether the daemon bridge is live at
		// startup. If register failed (daemon down, etc.) we still draw the
		// badge so the user knows Pockly is *trying* — yellow says "not
		// attached"; the bridge reconnect loop will flip it green if/when
		// the daemon comes up.
		initialAttached := bridge != nil
		indicator = newStatusIndicator(os.Stdout, writeStdout, initialAttached)
		defer indicator.close()
		go func() {
			time.Sleep(700 * time.Millisecond)
			indicator.paintNow()
		}()
	}

	if bridge != nil {
		if indicator != nil {
			bridge.SetStatusCallback(func(attached bool) {
				indicator.SetAttached(attached)
			})
		}
		defer bridge.Close()
		bridge.Emit("session_ready", "live", "awaiting_input", "", "")
	}
	var permissionWatcher *tuiPermissionWatcher
	if bridge != nil {
		permissionWatcher = bridge.permissionWatcher
	}
	modelConfirmer := newModelSwitchConfirmer(writePTY)

	// Prompt-ready detection for slash commands.
	//
	// turn_status normally returns to "awaiting_input" the moment Claude
	// replies: the web ends the run on the assistant message_added it sees
	// over the jsonl-watch. But a slash command (the model pill's
	// "/model X", or a typed "/clear") writes only a *user* jsonl record
	// and produces NO assistant turn, so nothing marks the turn done and
	// the session pins to "streaming" — the "/model → won't reply" bug.
	//
	// We must NOT use a blanket idle timer for this. PTY silence does not
	// mean the turn is done: Claude works silently between tokens, during
	// tool calls, and while the "✻ <verb>… (Ns · N tokens)" spinner ticks.
	// An idle-only detector fires prompt_ready in those gaps, the web
	// treats prompt_ready as turn-complete (finishLiveAgentRun), and the
	// Thinking/Working indicator vanishes mid-reply. So arm the detector
	// ONLY when the submitted input looks like a slash command, and emit a
	// single prompt_ready once that command's output settles. Normal
	// prompts never arm it and keep their pre-existing message_added-driven
	// completion.
	const promptReadyDelay = 1200 * time.Millisecond
	// promptReadyStatusFresh bounds how recent Claude's structured status must
	// be to override the idle timer (C8): a fresh non-idle status means a slash
	// command kicked off a long op with a PTY lull, so suppress the premature
	// "ready". Stale/absent status falls back to the idle heuristic.
	const promptReadyStatusFresh = 10 * time.Second
	lastPTYOutputNano.Store(time.Now().UnixNano())
	promptReadyArmed.Store(false)
	stopIdle := make(chan struct{})
	defer close(stopIdle)
	if bridge != nil {
		go func() {
			ticker := time.NewTicker(300 * time.Millisecond)
			defer ticker.Stop()
			for {
				select {
				case <-stopIdle:
					return
				case <-ticker.C:
					if !promptReadyArmed.Load() {
						continue
					}
					idle := time.Duration(time.Now().UnixNano() - lastPTYOutputNano.Load())
					if idle < promptReadyDelay {
						continue
					}
					// C8: cross-check the structured session status so a long
					// slash-command op (>1.2s PTY lull mid-work) isn't misread as
					// ready. Only a fresh, explicitly non-idle status holds it off.
					status, updatedAtMs := bridge.claudeSessionState()
					if shouldHoldPromptReady(status, updatedAtMs, time.Now(), promptReadyStatusFresh) {
						continue
					}
					promptReadyArmed.Store(false)
					bridge.Emit("prompt_ready", "live", "awaiting_input", "", "")
				}
			}
		}()
	}

	go func() {
		buf := make([]byte, 4096)
		for {
			n, err := ptmx.Read(buf)
			if n > 0 {
				chunk := append([]byte(nil), buf[:n]...)
				_, _ = writeStdout(chunk)
				// Refresh the prompt-ready idle clock. This only matters
				// while the detector is armed (after a slash command); a
				// normal turn never arms it, so this is just a store.
				lastPTYOutputNano.Store(time.Now().UnixNano())
				if permissionWatcher != nil {
					permissionWatcher.Feed(chunk)
				}
				modelConfirmer.Feed(chunk)
				// Raw PTY bytes are only for terminal mirrors. Web chat
				// ignores text_delta and renders structured message_added
				// events from Claude's JSONL instead, so ANSI/TUI frames
				// can safely flow to xterm.js without polluting bubbles.
				if bridge != nil {
					bridge.Emit("text_delta", "live", "streaming", string(chunk), "")
				}
				if indicator != nil {
					indicator.schedulePaint(120 * time.Millisecond)
				}
				//
				// Intentionally NOT calling indicator.maybePaint() here.
				// Pre-v0.1.34 we did, on every PTY read — meaning the
				// wrapper's "Pockly attached" badge tried to repaint
				// itself into the bottom-right corner during every
				// Claude TUI frame. PTY chunks routinely split a Claude
				// ANSI sequence mid-stream (e.g. one read ends in "\x1b[10;"
				// and the next starts "5HHello"); inserting our own
				// ESC[<row>;<col>H ... ESC8 sequence between them
				// fragmented Claude's cursor state and left ghost text
				// scattered across the screen ("r imits sage kills,…").
				// Now the indicator only paints on startup, resize, and
				// SetAttached state flips — none of which race the Claude
				// TUI's streaming repaints. claude-integrate's statusLine
				// already shows live Pockly status inline ("◆ Pockly ·
				// ⚡ PTY duplex · 1 paired"), so the bottom-right badge
				// is mostly redundant anyway; we keep it for users who
				// don't have the statusLine installed.
			}
			if err != nil {
				done <- err
				return
			}
		}
	}()

	go func() {
		reader := bufio.NewReader(os.Stdin)
		var line strings.Builder
		escState := 0
		buf := make([]byte, 1024)
		for {
			n, err := reader.Read(buf)
			if n > 0 {
				chunk := buf[:n]
				_, _ = writePTY(chunk)
				if bridge != nil {
					for _, b := range chunk {
						switch b {
						case '\r', '\n':
							text := strings.TrimSpace(line.String())
							if text != "" {
								bridge.Emit("user_input", "live", "submitted", text, "")
								if looksLikeSlashCommand(text) {
									armPromptReady()
								}
							}
							line.Reset()
						case 0x7f, '\b':
							current := line.String()
							if len(current) > 0 {
								line.Reset()
								line.WriteString(current[:len(current)-1])
							}
						case 0x1b:
							escState = 1
						default:
							if escState > 0 {
								escState = advanceANSIInputState(escState, b)
							} else if b >= 0x20 {
								line.WriteByte(b)
							}
						}
					}
				}
			}
			if err != nil {
				done <- err
				return
			}
		}
	}()

	stopResize := watchResize(ptmx, cfg, func() {
		if indicator != nil {
			indicator.paintNow()
		}
	})
	defer stopResize()

	// userInitiatedExit goes true the moment we forward SIGINT/SIGTERM to
	// claude on the user's behalf. Distinguishes "user pressed Ctrl+C"
	// (clean exit, no recovery wanted) from "claude crashed by itself"
	// (unclean exit, daemon may want to spawn a recovery SDK driver).
	var userInitiatedExit atomic.Bool
	stopSignals := forwardSignals(ptmx, cfg, func(os.Signal) {
		userInitiatedExit.Store(true)
	})
	defer stopSignals()

	err = <-done
	_ = ptmx.Close()
	waitErr := ptmx.Wait()
	// Classify the exit before any of the emit/exit-intent reporting so
	// we can hand the daemon a single accurate signal.
	exitCode, exitSignal := classifyExit(waitErr)
	clean := userInitiatedExit.Load() || exitCode == 0
	if bridge != nil {
		bridge.ReportExitIntent(exitIntent{
			Clean:           clean,
			UserInitiated:   userInitiatedExit.Load(),
			ExitCode:        exitCode,
			TerminatedBy:    exitSignal,
			ReportedFromPID: os.Getpid(),
		})
		bridge.Emit("session_exited", "exited", "idle", "", "")
	}
	if err != nil && !errors.Is(err, os.ErrClosed) && !strings.Contains(err.Error(), "input/output error") {
		return err
	}
	if exitCode != 0 || exitSignal != "" {
		os.Exit(exitCode)
	}
	return waitErr
}

// classifyExit extracts the exit code + terminating signal name (if any)
// from cmd.Wait()'s return value. exitCode=0 with empty signal means
// clean exit; non-zero or signal!="" means abnormal. Caller pairs this
// with userInitiatedExit to decide clean/unclean for exit_intent.
func classifyExit(waitErr error) (exitCode int, terminatedBy string) {
	if waitErr == nil {
		return 0, ""
	}
	exitErr, ok := waitErr.(*exec.ExitError)
	if !ok {
		type exitCoder interface {
			ExitCode() int
		}
		if coder, hasCode := waitErr.(exitCoder); hasCode {
			return coder.ExitCode(), ""
		}
		return -1, ""
	}
	status, ok := exitErr.Sys().(syscall.WaitStatus)
	if !ok {
		return exitErr.ExitCode(), ""
	}
	if status.Signaled() {
		return 128 + int(status.Signal()), status.Signal().String()
	}
	return status.ExitStatus(), ""
}

func attachLatestPocklyTerminal(cfg config) error {
	daemon, err := pocklyDaemonPath()
	if err != nil {
		return err
	}
	args := []string{
		"live-attach",
		"--daemon-url", defaultString(cfg.daemonURL, "http://127.0.0.1:8947"),
		"--latest",
		"--display", "raw",
	}
	cmd := exec.Command(daemon, args...)
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func pocklyDaemonPath() (string, error) {
	if explicit := strings.TrimSpace(os.Getenv("POCKLY_DAEMON")); explicit != "" {
		return explicit, nil
	}
	self, err := os.Executable()
	if err == nil {
		candidate := strings.TrimSuffix(self, "pockly-claude-wrapper") + "pockly-daemon"
		if _, statErr := os.Stat(candidate); statErr == nil {
			return candidate, nil
		}
	}
	return exec.LookPath("pockly-daemon")
}

func shouldPassThrough(args []string) bool {
	for _, arg := range args {
		switch arg {
		case "-p", "--print", "--version", "-v", "--help", "-h":
			return true
		}
	}
	return false
}

func execDirect(spec claudelauncher.CommandSpec, cwd string, args []string, env []string) error {
	cmd := exec.Command(spec.Path, spec.Args(args)...)
	cmd.Dir = cwd
	cmd.Env = env
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func wrapperEnvSnapshot() claudelauncher.EnvSnapshot {
	env := os.Environ()
	env = setEnv(env, "TERM", defaultString(os.Getenv("TERM"), "xterm-256color"))
	env = setEnv(env, "COLORTERM", defaultString(os.Getenv("COLORTERM"), "truecolor"))
	return claudelauncher.Env(env)
}

func setupScreen(cfg config) func() {
	if !term.IsTerminal(int(os.Stdout.Fd())) {
		return func() {}
	}
	if cfg.altScreen {
		fmt.Print("\x1b[?1049h")
	}
	if cfg.clear {
		fmt.Print("\x1b[H\x1b[2J")
		if cfg.altScreen {
			fmt.Print("\x1b[3J")
		}
	}
	return func() {
		if cfg.altScreen {
			fmt.Print("\x1b[?1049l")
		}
	}
}

func setupTerminal(cfg config) (func(), error) {
	if !cfg.rawMode || !term.IsTerminal(int(os.Stdin.Fd())) {
		return func() {}, nil
	}
	old, err := term.MakeRaw(int(os.Stdin.Fd()))
	if err != nil {
		return nil, err
	}
	return func() { _ = term.Restore(int(os.Stdin.Fd()), old) }, nil
}

type terminalSize struct {
	Cols uint16
	Rows uint16
}

type ptySession interface {
	io.ReadWriteCloser
	Resize(cols, rows uint16) error
	Pid() int
	Signal(os.Signal) error
	Wait() error
}

func currentSize() terminalSize {
	cols, rows, err := term.GetSize(int(os.Stdout.Fd()))
	if err != nil || cols <= 0 || rows <= 0 {
		cols, rows = 120, 36
	}
	return terminalSize{Cols: uint16(cols), Rows: uint16(rows)}
}

func watchResize(ptmx ptySession, cfg config, onResize func()) func() {
	sigch := make(chan os.Signal, 16)
	resizeSignals := terminalResizeSignals()
	if len(resizeSignals) == 0 {
		return func() {}
	}
	signal.Notify(sigch, resizeSignals...)
	apply := func() {
		size := currentSize()
		_ = ptmx.Resize(size.Cols, size.Rows)
		if cfg.debug {
			fmt.Fprintf(os.Stderr, "[pockly wrapper] resize %dx%d\n", size.Cols, size.Rows)
		}
		if onResize != nil {
			onResize()
		}
	}
	go func() {
		apply()
		for range sigch {
			apply()
		}
	}()
	return func() { signal.Stop(sigch); close(sigch) }
}

func forwardSignals(ptmx ptySession, cfg config, onSignal func(os.Signal)) func() {
	sigch := make(chan os.Signal, 16)
	signal.Notify(sigch, os.Interrupt, syscall.SIGTERM)
	go func() {
		for sig := range sigch {
			if onSignal != nil {
				onSignal(sig)
			}
			if cfg.debug {
				fmt.Fprintf(os.Stderr, "[pockly wrapper] signal %v\n", sig)
			}
			_ = ptmx.Signal(sig)
		}
	}()
	return func() { signal.Stop(sigch); close(sigch) }
}

// daemonBridge owns the wrapper's connection to the local Pockly daemon.
// It survives daemon restarts: any HTTP 404 on /events or /input-stream
// triggers a re-register (POST /api/dev/terminal-sessions) so the wrapper
// gets a fresh terminal_session_id from the new daemon process. Without
// that, a `launchctl bootout/bootstrap` (or any daemon crash + relaunch)
// silently severs every running wrapper — the wrapper keeps writing to
// 404 endpoints and the user has no clue until they try web→inject.
type daemonBridge struct {
	client *http.Client
	base   string
	cwd    string
	done   chan struct{}
	pid    int // claude child pid; 0 if not yet known

	mu        sync.RWMutex
	id        string // mutates on re-register
	sessionID string // mutates whenever watchActiveSessionID detects the active jsonl changed

	// lockedSessionID is the UUID the wrapper bound to BEFORE exec'ing
	// claude (v0.1.36): generated + injected via --session-id, parsed
	// out of --resume <sid>, or pre-resolved from --continue. When
	// non-empty the watcher skips fd discovery entirely and tails only
	// projectDir/<lockedSessionID>.jsonl. Empty for --fork-session,
	// where claude picks the sid and we fall back to legacy discovery.
	lockedSessionID string

	onStatusChange func(attached bool) // optional: notified after every register/re-register success or failure

	// v0.2.2: in-memory queue of events whose initial Emit attempt (and
	// retries) failed. Drained by:
	//   - next Emit() call (drainPending fires first thing)
	//   - keepaliveLoop ticker (every 10s, even when no jsonl activity)
	// Cap is hard-coded at 200 to bound memory if daemon is permanently
	// down — older entries get dropped (with a stderr warning) once full,
	// since extreme backpressure means we've lost sync anyway.
	pendingMu sync.Mutex
	pending   []pendingEmit

	permissionWatcher *tuiPermissionWatcher

	emittedMu          sync.Mutex
	emittedMessageKeys map[string]struct{}
}

// pendingEmit captures one Emit-payload that failed delivery and is
// awaiting retry. Mirrors the Emit() signature exactly.
type pendingEmit struct {
	kind          string
	sessionStatus string
	turnStatus    string
	payload       string
	errorText     string
}

// pendingEmitMax caps the in-memory backlog. 200 is enough to survive
// a few-minute daemon restart in a chatty session without OOM but small
// enough that a permanently-down daemon won't leak.
const pendingEmitMax = 200

func maybeStartDaemonBridge(cfg config, cwd string, invocation claudeInvocation, writePTY func([]byte) (int, error), childStartedAt time.Time, childPID int) (*daemonBridge, error) {
	if !cfg.register || os.Getenv("POCKLY_CLAUDE_REGISTER") == "0" {
		return nil, nil
	}
	base := strings.TrimRight(defaultString(cfg.daemonURL, "http://127.0.0.1:8947"), "/")
	// invocation.sessionID is the pre-bound UUID from resolveLockedSessionID
	// when invocation.lockable=true (which covers every CLI form except
	// --fork-session). Both the immediately-known sessionID (used for the
	// initial register) and the lockedSessionID (used by the watcher to
	// skip fd discovery) start as the same value; the watcher only deviates
	// when lockedSessionID is empty.
	lockedSID := ""
	if invocation.lockable {
		lockedSID = invocation.sessionID
	}
	bridge := &daemonBridge{
		client:          &http.Client{},
		base:            base,
		sessionID:       invocation.sessionID,
		lockedSessionID: lockedSID,
		cwd:             cwd,
		pid:             childPID,
		done:            make(chan struct{}),
	}
	bridge.permissionWatcher = newTUIPermissionWatcher(bridge, writePTY)
	id, err := bridge.registerTerminalSession()
	if err != nil {
		return nil, err
	}
	bridge.mu.Lock()
	bridge.id = id
	bridge.mu.Unlock()
	bridge.Emit("session_started", "live", "awaiting_input", "", "")
	go bridge.readInputs(writePTY)
	// Always watch — even with --resume (which seeds sessionID from the CLI
	// arg), claude can rotate sids in-app via /resume, /clear, /new etc.
	// The old latch-once discovery silently routed inject text into a stale
	// jsonl after any such rotation; the watcher rebinds on every change.
	go bridge.watchActiveSessionID(cwd, childPID, childStartedAt)
	// Keepalive on a slower cadence than rebind polling. The relay marks
	// terminal_sessions disconnected after ~45s without a keepalive so
	// SIGKILL'd / OOM'd / network-partitioned wrappers stop showing up
	// as "writable" in the web UI. Picked 10s as the heartbeat per the
	// session design (4x slack at 45s threshold).
	go bridge.keepaliveLoop()
	return bridge, nil
}

// registerTerminalSession POSTs to /api/dev/terminal-sessions and returns the
// daemon-assigned terminal_session_id. Called both at wrapper startup and
// during reconnect (when the daemon was restarted and has no memory of us).
// Carries claude_pid so the daemon can wire it onto the ExternalSession
// for inject-time fd verification.
func (b *daemonBridge) registerTerminalSession() (string, error) {
	body, _ := json.Marshal(map[string]any{"claude_pid": b.pid})
	resp, err := b.client.Post(b.base+"/api/dev/terminal-sessions", "application/json", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", fmt.Errorf("register external terminal: %s", resp.Status)
	}
	var decoded struct {
		TerminalSession struct {
			ID string `json:"id"`
		} `json:"terminal_session"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&decoded); err != nil {
		return "", err
	}
	if decoded.TerminalSession.ID == "" {
		return "", fmt.Errorf("register external terminal: missing id")
	}
	return decoded.TerminalSession.ID, nil
}

// reregister fetches a fresh id from the (presumably restarted) daemon and
// replays session_started so the daemon side rebinds metadata and the relay
// sees the wrapper as live again. Returns the new id on success.
func (b *daemonBridge) reregister() error {
	newID, err := b.registerTerminalSession()
	if err != nil {
		return err
	}
	b.mu.Lock()
	b.id = newID
	b.mu.Unlock()
	b.Emit("session_started", "live", "awaiting_input", "", "")
	return nil
}

func (b *daemonBridge) currentID() string {
	b.mu.RLock()
	defer b.mu.RUnlock()
	return b.id
}

// ClaudeSessionID returns the wrapper's discovered Claude session_id (or "").
func (b *daemonBridge) ClaudeSessionID() string {
	b.mu.RLock()
	defer b.mu.RUnlock()
	return b.sessionID
}

// updateClaudeSessionID swaps the bound sid and reports whether it
// actually changed plus the previous value. Watch-driven rebinding uses
// the (changed, prev) return so it can suppress a redundant rebound emit
// when claude's open-fd hasn't moved.
func (b *daemonBridge) updateClaudeSessionID(sid string) (changed bool, prev string) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if sid == b.sessionID {
		return false, sid
	}
	prev = b.sessionID
	b.sessionID = sid
	return true, prev
}

// SetStatusCallback wires the bridge to a status-indicator (or any observer)
// that wants to know when the daemon connection drops or recovers. Called
// after register/re-register attempts. Never called from inside b.mu held.
func (b *daemonBridge) SetStatusCallback(cb func(attached bool)) {
	b.mu.Lock()
	b.onStatusChange = cb
	b.mu.Unlock()
}

func (b *daemonBridge) notifyStatus(attached bool) {
	b.mu.RLock()
	cb := b.onStatusChange
	b.mu.RUnlock()
	if cb != nil {
		cb(attached)
	}
}

// watchActiveSessionID runs for the lifetime of the wrapper, polling the
// claude child's open-fd table to discover which jsonl it's currently
// writing. The basename of that file IS the active session_id. On every
// change (first discovery OR rotation via in-app /resume etc.) we update
// the cached sid and Emit so the daemon and relay learn the new binding.
//
// Replaces the old mtime-based one-shot discovery, which had three fatal
// gaps:
//   - latch-once: a single successful discovery, then never re-checked,
//     so /resume rotations silently broke the binding;
//   - 60s deadline: slow-starting claudes never got bound;
//   - guesswork across concurrent claudes in the same cwd: mtime alone
//     can't tell two jsonls apart.
//
// setupPermissionMCP writes a temporary mcp-config JSON that registers
// pockly's permission MCP server, and returns the CLI flags claude
// needs to pick it up: `--mcp-config <path>` + `--permission-prompt-tool
// mcp__pockly__request_permission`. Returns ("", nil, nil) silently
// when the pockly-daemon binary can't be located — wrapper still works
// without the permission relay, just without the web "claude is doing X"
// card.
//
// v0.1.42: the MCP server (a subcommand of pockly-daemon) auto-allows
// every request but POSTs the (tool, input) to the daemon so the web
// can render it. v0.2.0 will replace auto-allow with a real wait-for-
// web-decision flow.
//
// claude code spec for permission-prompt-tool: the value must be the
// MCP tool name in `mcp__<servername>__<toolname>` form. Our server
// is registered as "pockly", the tool is "request_permission".
func setupPermissionMCP(sessionID string) (string, func(), []string) {
	daemonBin := resolvePocklyDaemonPath()
	if daemonBin == "" {
		return "", nil, nil
	}
	tmp, err := os.CreateTemp("", "pockly-mcp-config-*.json")
	if err != nil {
		return "", nil, nil
	}
	config := map[string]any{
		"mcpServers": map[string]any{
			"pockly": map[string]any{
				"command": daemonBin,
				"args": []string{
					"mcp-permission",
					"--session-id", sessionID,
					// v0.2.0: enable interactive flow (register → await
					// web decision → translate to allow/deny). The
					// daemon needs to be v0.2.0+ to expose the
					// /api/dev/permission-requests endpoints; if it
					// isn't, register fails fast and the MCP server
					// falls back to deny rather than hanging. So
					// wrapper-version => MCP behavior, not daemon
					// version — but daemon version is also auto-
					// updated, so the matched-pair invariant holds.
					"--interactive",
				},
			},
		},
	}
	if err := json.NewEncoder(tmp).Encode(config); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmp.Name())
		return "", nil, nil
	}
	_ = tmp.Close()
	path := tmp.Name()
	cleanup := func() { _ = os.Remove(path) }
	args := []string{
		"--mcp-config", path,
		"--permission-prompt-tool", "mcp__pockly__request_permission",
	}
	return path, cleanup, args
}

// resolvePocklyDaemonPath finds the pockly-daemon binary. Strategy:
//  1. absolute path next to the running wrapper binary (typical
//     /usr/local/bin install where both binaries live together);
//  2. PATH lookup fallback. Returns "" if neither resolves — caller
//     silently disables the permission MCP rather than crashing.
func resolvePocklyDaemonPath() string {
	if exe, err := os.Executable(); err == nil {
		candidate := filepath.Join(filepath.Dir(exe), "pockly-daemon")
		if _, err := os.Stat(candidate); err == nil {
			return candidate
		}
	}
	if found, err := exec.LookPath("pockly-daemon"); err == nil {
		return found
	}
	return ""
}

// claudeProjectDir mirrors claude code's own filename encoding:
// `~/.claude/projects/<cwd-with-separators-replaced-by-dashes>/`. Returns
// "" when home isn't resolvable or cwd encodes to empty.
func claudeProjectDir(cwd string) string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	encoded := encodeClaudeProjectDirName(cwd)
	if encoded == "" {
		return ""
	}
	return filepath.Join(home, ".claude", "projects", encoded)
}

func encodeClaudeProjectDirName(cwd string) string {
	encoded := strings.TrimRight(cwd, `/\`)
	encoded = strings.ReplaceAll(encoded, "\\", "-")
	encoded = strings.ReplaceAll(encoded, "/", "-")
	encoded = strings.ReplaceAll(encoded, ":", "-")
	return encoded
}

// watchActiveSessionID owns the session-to-jsonl binding for the
// lifetime of the wrapper. There are two modes:
//
//  1. **Locked** (v0.1.36, the happy path): the wrapper pre-bound a UUID
//     before exec'ing claude via resolveLockedSessionID. We know the
//     jsonl path is `projectDir/<lockedSID>.jsonl` and tail ONLY that
//     file. No discovery, no rotation, no cross-binding risk even when
//     N concurrent claudes share the cwd. The first record we read
//     gets a content-check: its sessionId field must equal the locked
//     UUID, else fail loud (claude version drift, --session-id ignored).
//
//  2. **Discovery** (only for `--fork-session`): claude generates its
//     own sid we can't know ahead of time. Falls back to the legacy
//     fd-discovery path; rotation is allowed but logged as
//     session_rebound.
func (b *daemonBridge) watchActiveSessionID(cwd string, pid int, childStartedAt time.Time) {
	projectDir := claudeProjectDir(cwd)
	if projectDir == "" {
		return
	}
	b.mu.RLock()
	locked := b.lockedSessionID
	b.mu.RUnlock()
	if locked != "" {
		b.watchLockedJSONL(projectDir, locked, pid)
		return
	}
	b.watchDiscoveredJSONL(projectDir, pid, childStartedAt)
}

// watchLockedJSONL is the v0.1.36 happy path: the wrapper-generated UUID +
// `--session-id <uuid>` flag is the authoritative initial binding, so we tail
// that one file directly (no mtime newest-wins guessing — that's what avoids
// cross-binding when N claudes share a cwd).
//
// #34: we DO follow in-app rotation (/resume, /clear, /new) — claude keeps the
// same pid but starts writing a different <sid>.jsonl, and without this the web
// inject binding goes stale (mirrors/injects the old session). Rotation is
// detected with the FD-based, pid-scoped activeJSONL (the jsonl THIS pid
// actually has open), which cannot cross-bind to a sibling claude. We
// deliberately do NOT use the mtime fallback here; if FD discovery is
// unavailable we keep the locked sid (the prior no-rotation behavior) rather
// than risk binding a sibling's newest jsonl.
//
// We also do one paranoia check: when the jsonl first appears, read the
// first record and verify its `sessionId` field matches our locked
// UUID. If it doesn't, claude ignored --session-id (version drift?
// flag deprecated?) and we shouldn't keep silently mirroring the wrong
// data. Fail loud with a session_exited error event so the web stops
// showing a broken live stream.
func (b *daemonBridge) watchLockedJSONL(projectDir, sid string, pid int) {
	jsonlPath := projectDir + "/" + sid + ".jsonl"
	tailer := newJSONLTailer()
	wake, werr := b.startJSONLWatcher(projectDir, jsonlPath)
	tickInterval := 1 * time.Second
	if werr == nil {
		tickInterval = 5 * time.Second
	} else {
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] fsnotify unavailable, polling jsonl at 1s: %v\n", werr)
	}
	tick := time.NewTicker(tickInterval)
	defer tick.Stop()
	verified := false
	for {
		// #34: follow in-app rotation (/resume, /clear, /new). activeJSONL is
		// FD-based + pid-scoped, so a different active jsonl for THIS pid means
		// claude rotated — rebind to it so inject + mirroring track the new
		// session. FD-only (no mtime fallback) keeps the no-cross-binding
		// guarantee; if FD discovery is unavailable activeJSONL returns ok=false
		// and we stay on the locked sid (prior behavior). The common no-rotation
		// case returns activeSid == sid, so this is a no-op there.
		if activeSid, activePath, ok := activeJSONL(pid, projectDir); ok && activeSid != "" && activeSid != sid {
			b.Emit("session_rebound", "live", "awaiting_input",
				fmt.Sprintf("prev=%s active=%s pid=%d (in-app rotation)", sid, activeSid, pid), "")
			sid, jsonlPath = activeSid, activePath
			tailer.reset(jsonlPath)
		}
		// Make the initial session_started emit eager (don't wait for
		// the first jsonl line); the relay needs the binding registered
		// so inject can route. updateClaudeSessionID returns changed=false
		// on subsequent ticks once already-set.
		if changed, prev := b.updateClaudeSessionID(sid); changed && prev == "" {
			b.Emit("session_started", "live", "awaiting_input", "", "")
		}
		_, _ = tailer.tail(jsonlPath, func(rec map[string]any, raw []byte) {
			if !verified {
				if got, _ := rec["sessionId"].(string); got != "" && got != sid {
					// Claude wrote a record with a different sid than
					// the one we passed via --session-id. Possible
					// causes: flag was renamed/removed, user passed
					// conflicting flags, claude internally rebound.
					// Stop the stream loudly so the web doesn't keep
					// rendering mismatched content.
					b.Emit("error", "error", "idle", "",
						fmt.Sprintf("session_id_mismatch: expected %s got %s — claude may have ignored --session-id", sid, got))
					return
				}
				verified = true
			}
			if b.permissionWatcher != nil {
				b.permissionWatcher.ObserveJSONLRecord(rec)
			}
			sawAssistantText := false
			for _, event := range extractMessageEvents(rec) {
				if event.Role == "" {
					continue
				}
				if !b.rememberMessageEvent(event) {
					continue
				}
				payload, _ := json.Marshal(event)
				b.Emit("message_added", "live", "streaming", string(payload), "")
				if event.Role == "assistant" && strings.TrimSpace(event.Text) != "" {
					sawAssistantText = true
				}
			}
			if sawAssistantText {
				b.Emit("prompt_ready", "live", "awaiting_input", "", "")
			}
		})
		select {
		case <-b.done:
			return
		case <-tick.C:
		case <-wake:
		}
	}
}

// watchDiscoveredJSONL is the legacy fd-discovery path, retained only
// for `--fork-session` (where claude generates its own sid). Everything
// else hits watchLockedJSONL above.
func (b *daemonBridge) watchDiscoveredJSONL(projectDir string, pid int, childStartedAt time.Time) {
	tailer := newJSONLTailer()
	wake, werr := b.startJSONLWatcher(projectDir, "")
	tickInterval := 1 * time.Second
	if werr == nil {
		tickInterval = 5 * time.Second
	} else {
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] fsnotify unavailable, polling jsonl at 1s: %v\n", werr)
	}
	tick := time.NewTicker(tickInterval)
	defer tick.Stop()
	for {
		sid, jsonlPath := b.resolveActiveSession(pid, projectDir, childStartedAt)
		if sid != "" {
			if changed, prev := b.updateClaudeSessionID(sid); changed {
				if prev == "" {
					b.Emit("session_started", "live", "awaiting_input", "", "")
				} else {
					b.Emit("session_rebound", "live", "awaiting_input",
						fmt.Sprintf("prev=%s jsonl=%s pid=%d", prev, jsonlPath, pid), "")
					tailer.reset(jsonlPath)
				}
			}
			if jsonlPath != "" {
				_, _ = tailer.tail(jsonlPath, func(rec map[string]any, raw []byte) {
					if b.permissionWatcher != nil {
						b.permissionWatcher.ObserveJSONLRecord(rec)
					}
					sawAssistantText := false
					for _, event := range extractMessageEvents(rec) {
						if event.Role == "" {
							continue
						}
						if !b.rememberMessageEvent(event) {
							continue
						}
						payload, _ := json.Marshal(event)
						b.Emit("message_added", "live", "streaming", string(payload), "")
						if event.Role == "assistant" && strings.TrimSpace(event.Text) != "" {
							sawAssistantText = true
						}
					}
					if sawAssistantText {
						b.Emit("prompt_ready", "live", "awaiting_input", "", "")
					}
				})
			}
		}
		select {
		case <-b.done:
			return
		case <-tick.C:
		case <-wake:
		}
	}
}

// startJSONLWatcher wires up an fsnotify directory watch on projectDir
// and returns a wake channel that fires (debounced via channel-of-1)
// when a relevant .jsonl event arrives. matchPath, if non-empty,
// filters to just that single file path; empty means any .jsonl event
// in the directory wakes (used by the legacy discovery path that
// doesn't know the sid yet).
//
// Returns (nil, err) when fsnotify can't start — caller falls back to
// pure polling. fsnotify can legitimately fail in containers without
// inotify, on sandboxed filesystems, or if projectDir doesn't yet
// exist. The watcher goroutine self-closes on b.done.
func (b *daemonBridge) startJSONLWatcher(projectDir, matchPath string) (<-chan struct{}, error) {
	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return nil, err
	}
	if err := watcher.Add(projectDir); err != nil {
		_ = watcher.Close()
		return nil, err
	}
	wake := make(chan struct{}, 1)
	go func() {
		defer watcher.Close()
		for {
			select {
			case <-b.done:
				return
			case ev, ok := <-watcher.Events:
				if !ok {
					return
				}
				if ev.Op&(fsnotify.Write|fsnotify.Create) == 0 {
					continue
				}
				if matchPath != "" {
					if ev.Name != matchPath {
						continue
					}
				} else if !strings.HasSuffix(ev.Name, ".jsonl") {
					continue
				}
				select {
				case wake <- struct{}{}:
				default:
				}
			case err, ok := <-watcher.Errors:
				if !ok {
					return
				}
				fmt.Fprintf(os.Stderr, "[pockly-wrapper] jsonl watcher error: %v\n", err)
			}
		}
	}()
	return wake, nil
}

// resolveActiveSession returns the jsonl that the wrapper's child
// claude PID currently has an open write fd on, scoped to projectDir.
//
// v0.1.36 removed the mtime fallback that used to follow fd-discovery.
// Reasoning: this function is now only reached by the `--fork-session`
// path (claude generates a new sid we can't predict). In that mode, if
// fd-discovery fails — container without lsof / locked-down /proc — the
// honest answer is "we don't know which jsonl is ours", and the right
// behavior is to go silent rather than guess by mtime and risk binding
// to a SIBLING claude's session running in the same cwd. The mtime path
// (newestJSONLAfter) is retained as a building block for the
// --continue pre-resolution in resolveLockedSessionID, where "newest"
// is genuinely what the user asked for.
func (b *daemonBridge) resolveActiveSession(pid int, projectDir string, childStartedAt time.Time) (string, string) {
	if sid, path, ok := activeJSONL(pid, projectDir); ok {
		return sid, path
	}
	return "", ""
}

// newestJSONLAfter is the mtime-based fallback. Returns the .jsonl in
// projectDir with the latest mtime that's ≥ startedAt, so jsonls from
// long-dead previous claude runs don't get picked up. Filters out jsonls
// whose entrypoint marker shows they belong to Claude Desktop or other
// non-CLI producers — those share the project directory but aren't
// driveable by the wrapper's PTY. See jsonl_entrypoint.go for the
// rationale; the canonical scenario is "user runs Claude Desktop in one
// window and CLI claude /resume in another; Desktop keeps bumping its
// jsonl's mtime, so naive newest-wins binds PTY to a phantom session."
func newestJSONLAfter(projectDir string, startedAt time.Time) (string, string, bool) {
	entries, err := os.ReadDir(projectDir)
	if err != nil {
		return "", "", false
	}
	var bestName string
	var bestPath string
	var bestMtime time.Time
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasSuffix(name, ".jsonl") {
			continue
		}
		info, statErr := entry.Info()
		if statErr != nil {
			continue
		}
		if info.ModTime().Before(startedAt) {
			continue
		}
		path := projectDir + "/" + name
		if !jsonlOwnsCLI(path) {
			continue
		}
		if bestName == "" || info.ModTime().After(bestMtime) {
			bestName = name
			bestPath = path
			bestMtime = info.ModTime()
		}
	}
	if bestName == "" {
		return "", "", false
	}
	sid := strings.TrimSuffix(bestName, ".jsonl")
	return sid, bestPath, sid != ""
}

// Emit posts a single event to the daemon. v0.2.2 hardening:
//
//   - First drain any prior failed events queued in `pending` — they
//     get retried in FIFO order before the fresh event so order is
//     preserved across the brief outage window.
//   - 4 attempts with exponential backoff (0, 200ms, 400ms, 800ms) on
//     transport errors AND 5xx responses. 4xx (other than 404) is
//     non-retriable (auth/permission won't fix by waiting).
//   - 404 → re-register + retry (the v0.1.37 daemon-restart path).
//   - On final failure, stash in `pending` (capped at 200) and log to
//     stderr. The wrapper indicator goes yellow but the event isn't
//     lost — next Emit or 10s keepalive tick drains the queue.
//
// Pre-v0.2.2 this method silently dropped events on transport / 5xx,
// which manifested as #150: web missing turns even though daemon's
// jsonl index had them.
func (b *daemonBridge) Emit(kind, sessionStatus, turnStatus, payload, errorText string) {
	if b == nil {
		return
	}
	// Drain backlog first so order is preserved (older events emit
	// before the new one).
	b.drainPending()
	if !b.emitWithRetry(kind, sessionStatus, turnStatus, payload, errorText) {
		b.queuePending(pendingEmit{kind, sessionStatus, turnStatus, payload, errorText})
	}
}

// exitIntent is the wrapper's last-words report to daemon. Sent right
// before the wrapper process itself exits, so daemon can later
// distinguish "user pressed Ctrl+C / typed /quit" from "claude
// crashed" without needing to fingerprint the silence after-the-fact.
// JSON-encoded into the body of POST /api/dev/terminal-sessions/<id>/exit-intent.
type exitIntent struct {
	// Clean true when the exit was user-initiated (SIGINT/SIGTERM
	// forwarded) OR claude exited normally with code 0.
	// daemon-side recovery logic only fires when Clean is false.
	Clean bool `json:"clean"`
	// UserInitiated true when the wrapper observed SIGINT or SIGTERM
	// directed at the wrapper itself before claude exited. Distinct
	// from Clean: a user could send SIGTERM and claude could still
	// hit a non-zero exit code (e.g. mid-write), but we still treat
	// the whole thing as user-initiated and skip recovery.
	UserInitiated bool `json:"user_initiated"`
	// ExitCode is the child's exit code (0 = clean, >0 = error,
	// 128+sig = killed-by-signal). -1 when wait() returned a
	// non-ExitError (rare; process disappeared before reap).
	ExitCode int `json:"exit_code"`
	// TerminatedBy names the POSIX signal that ended the process,
	// when applicable (e.g. "killed", "segmentation fault"). Empty
	// for normal-exit cases.
	TerminatedBy string `json:"terminated_by,omitempty"`
	// ReportedFromPID is the wrapper PID at exit time — helps
	// daemon-side telemetry correlate this report with the right
	// wrapper instance when it lands.
	ReportedFromPID int `json:"reported_from_pid,omitempty"`
}

// ReportExitIntent best-effort POSTs the wrapper's classification of
// its own exit to the daemon. Best-effort because the wrapper is about
// to exit itself — we don't retry, don't queue, and don't fail the
// process if it doesn't land. Daemon's recovery logic falls back to
// "assume unclean" when no intent shows up before the keepalive timer
// flips the session to disconnected anyway.
func (b *daemonBridge) ReportExitIntent(intent exitIntent) {
	if b == nil {
		return
	}
	id := b.currentID()
	if id == "" {
		return
	}
	body, err := json.Marshal(intent)
	if err != nil {
		return
	}
	url := b.base + "/api/dev/terminal-sessions/" + id + "/exit-intent"
	req, err := http.NewRequest(http.MethodPost, url, bytes.NewReader(body))
	if err != nil {
		return
	}
	req.Header.Set("Content-Type", "application/json")
	// 2s ceiling: enough for a localhost POST under load, short enough
	// that a stuck daemon doesn't strand the wrapper at exit.
	client := *b.client
	client.Timeout = 2 * time.Second
	resp, err := client.Do(req)
	if err != nil {
		return
	}
	_ = resp.Body.Close()
}

// emitWithRetry attempts up to 4 sends (immediate + 200/400/800ms
// backoff). Returns true on success, false on permanent failure.
// "Success" = 2xx response. "Permanent failure" = exhausted retries OR
// hit a non-retriable 4xx (other than 404). 404 triggers a re-register
// attempt + one more emit per retry slot.
func (b *daemonBridge) emitWithRetry(kind, sessionStatus, turnStatus, payload, errorText string) bool {
	backoffs := []time.Duration{0, 200 * time.Millisecond, 400 * time.Millisecond, 800 * time.Millisecond}
	for i, wait := range backoffs {
		if wait > 0 {
			time.Sleep(wait)
		}
		status, sendErr := b.emitOnce(kind, sessionStatus, turnStatus, payload, errorText)
		if sendErr != nil {
			// Transport error — daemon likely restarting. Retry.
			if i == len(backoffs)-1 {
				b.notifyStatus(false)
				fmt.Fprintf(os.Stderr, "[pockly-wrapper] emit transport error after %d tries: kind=%s err=%v\n", len(backoffs), kind, sendErr)
				return false
			}
			continue
		}
		if status == http.StatusNotFound {
			// Daemon forgot us — re-register + retry on next slot.
			if rerr := b.reregister(); rerr != nil {
				if i == len(backoffs)-1 {
					b.notifyStatus(false)
					fmt.Fprintf(os.Stderr, "[pockly-wrapper] emit re-register failed: kind=%s err=%v\n", kind, rerr)
					return false
				}
				continue
			}
			b.notifyStatus(true)
			// Retry immediately with the new id (no extra backoff —
			// re-register itself already took some ms).
			retryStatus, retryErr := b.emitOnce(kind, sessionStatus, turnStatus, payload, errorText)
			if retryErr == nil && retryStatus >= 200 && retryStatus < 300 {
				return true
			}
			if i == len(backoffs)-1 {
				fmt.Fprintf(os.Stderr, "[pockly-wrapper] emit failed after re-register: kind=%s status=%d err=%v\n", kind, retryStatus, retryErr)
				return false
			}
			continue
		}
		if status >= 500 {
			// 5xx — daemon/relay temporarily wedged. Retry.
			if i == len(backoffs)-1 {
				b.notifyStatus(false)
				fmt.Fprintf(os.Stderr, "[pockly-wrapper] emit %d after %d tries: kind=%s\n", status, len(backoffs), kind)
				return false
			}
			continue
		}
		if status >= 200 && status < 300 {
			b.notifyStatus(true)
			return true
		}
		// 4xx other than 404 — auth/permission, not retriable. Drop
		// loudly: this means the wire is broken (wrong audience, bad
		// JSON, etc.) and queueing won't help.
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] emit non-retriable %d: kind=%s (event dropped, not queued)\n", status, kind)
		return true // returning true so caller doesn't queue — there's no point
	}
	return false
}

// queuePending stashes a failed event for later retry. Capped at
// pendingEmitMax to bound memory; when full, drops the OLDEST (FIFO)
// so the most recent events have the best chance of eventually
// landing.
func (b *daemonBridge) queuePending(p pendingEmit) {
	b.pendingMu.Lock()
	defer b.pendingMu.Unlock()
	if len(b.pending) >= pendingEmitMax {
		// Slide the window — drop oldest. Use copy to keep the slice
		// from growing unbounded.
		copy(b.pending, b.pending[1:])
		b.pending = b.pending[:len(b.pending)-1]
		fmt.Fprintf(os.Stderr, "[pockly-wrapper] pending queue full (%d), dropped oldest\n", pendingEmitMax)
	}
	b.pending = append(b.pending, p)
}

// drainPending tries to flush any queued events. Stops on the first
// failure (puts the rest back) so FIFO order is preserved. Called by
// Emit() and keepaliveLoop().
func (b *daemonBridge) drainPending() {
	b.pendingMu.Lock()
	if len(b.pending) == 0 {
		b.pendingMu.Unlock()
		return
	}
	pending := b.pending
	b.pending = nil
	b.pendingMu.Unlock()

	for i, p := range pending {
		if !b.emitWithRetry(p.kind, p.sessionStatus, p.turnStatus, p.payload, p.errorText) {
			// Put the failed one + everything after it back at the
			// FRONT of the queue.
			b.pendingMu.Lock()
			b.pending = append(pending[i:], b.pending...)
			b.pendingMu.Unlock()
			return
		}
	}
}

// keepaliveLoop ticks every 10s to ping the daemon (which forwards to
// the relay). The relay's stale-terminal reaper looks for keepalives
// within the last 45s; missing 4 in a row marks the session
// disconnected. We use a dedicated endpoint instead of piggy-backing on
// Emit so the relay can track liveness independently of whether the
// wrapper has anything to say.
func (b *daemonBridge) keepaliveLoop() {
	if b == nil {
		return
	}
	tick := time.NewTicker(10 * time.Second)
	defer tick.Stop()
	// Fire immediately so the first keepalive lands at ~register time
	// rather than ~10s in.
	b.sendKeepalive()
	for {
		select {
		case <-b.done:
			return
		case <-tick.C:
			b.sendKeepalive()
			// v0.2.2: also drain any pending Emit backlog. The Emit
			// path drains-on-call, but if no jsonl activity happens
			// for a while (idle session) backlog would just sit. The
			// keepalive tick is the natural place to retry — it
			// already requires daemon reachability.
			b.drainPending()
		}
	}
}

// sendKeepalive POSTs to the daemon's keepalive endpoint. On 404
// (daemon restarted, forgot us) it falls through to the same
// re-register + retry dance Emit uses.
func (b *daemonBridge) sendKeepalive() {
	id := b.currentID()
	if id == "" {
		return
	}
	req, err := http.NewRequest(http.MethodPost, b.base+"/api/dev/terminal-sessions/"+id+"/keepalive", nil)
	if err != nil {
		return
	}
	resp, err := b.client.Do(req)
	if err != nil {
		return
	}
	defer resp.Body.Close()
	if resp.StatusCode == http.StatusNotFound {
		if rerr := b.reregister(); rerr != nil {
			return
		}
		// One retry on the new id.
		id = b.currentID()
		retry, retryErr := http.NewRequest(http.MethodPost, b.base+"/api/dev/terminal-sessions/"+id+"/keepalive", nil)
		if retryErr != nil {
			return
		}
		retryResp, retryDoErr := b.client.Do(retry)
		if retryDoErr != nil {
			return
		}
		retryResp.Body.Close()
	}
}

// emitOnce is the inner HTTP call. Returns the response status (0 if a
// transport error occurred). Caller decides whether to retry / re-register.
func (b *daemonBridge) emitOnce(kind, sessionStatus, turnStatus, payload, errorText string) (int, error) {
	id := b.currentID()
	body, _ := json.Marshal(map[string]string{
		"kind":           kind,
		"session_status": sessionStatus,
		"turn_status":    turnStatus,
		"payload":        payload,
		"error":          errorText,
		"session_id":     b.ClaudeSessionID(),
		"agent":          "claude-code",
		"cwd":            b.cwd,
	})
	req, err := http.NewRequest(http.MethodPost, b.base+"/api/dev/terminal-sessions/"+id+"/events", bytes.NewReader(body))
	if err != nil {
		return 0, err
	}
	req.Header.Set("Content-Type", "application/json")
	resp, err := b.client.Do(req)
	if err != nil {
		return 0, err
	}
	defer resp.Body.Close()
	return resp.StatusCode, nil
}

func (b *daemonBridge) Close() {
	if b == nil {
		return
	}
	select {
	case <-b.done:
	default:
		close(b.done)
	}
}

// tuiPermissionWatcher bridges Claude Code's native PTY approval sheet
// into the same permission_request flow used by the SDK/MCP path.
//
// Claude's interactive TUI does not reliably invoke --permission-prompt-tool
// for the 1/2/3 approval sheet. The only source of truth in PTY mode is the
// rendered terminal frame, so we detect that frame, register a pending request
// with the daemon, emit a permission_request event for web, then translate the
// web decision back into the keystroke Claude expects.
type tuiPermissionWatcher struct {
	bridge        *daemonBridge
	write         func([]byte) (int, error)
	timeout       time.Duration
	fallbackDelay time.Duration
	recentTTL     time.Duration

	mu              sync.Mutex
	buffer          string
	pendingTail     []byte // incomplete ANSI escape / UTF-8 rune carried to the next Feed
	driftReported   bool   // one-shot guard for the "waiting but unrecognized" drift signal
	active          map[string]struct{}
	recent          map[string]time.Time
	fallbackTimers  map[string]*time.Timer
	toolUseFallback map[string]string
}

type tuiPermissionPrompt struct {
	ToolName  string
	Input     map[string]any
	Sig       string
	ToolUseID string
	LocalOnly bool
	// AllowKey / DenyKey are the option numbers parsed from the prompt's
	// numbered list (e.g. "1. Yes" → AllowKey "1", "3. No" → DenyKey "3"). The
	// keystroke that forwards a web decision is derived from these rather than
	// hard-coded 1/3, so a build that renumbers/reorders the options still maps
	// Approve/Deny to the right choice. Empty → caller falls back to 1/3.
	AllowKey string
	DenyKey  string
}

var tuiToolLineRE = regexp.MustCompile(`(?m)[●⏺]\s*([A-Za-z][A-Za-z0-9_ -]*)(?:\(([^)\r\n]*)\))?`)

func newTUIPermissionWatcher(bridge *daemonBridge, write func([]byte) (int, error)) *tuiPermissionWatcher {
	return &tuiPermissionWatcher{
		bridge:          bridge,
		write:           write,
		timeout:         30 * time.Second,
		fallbackDelay:   1500 * time.Millisecond,
		recentTTL:       2 * time.Second,
		active:          make(map[string]struct{}),
		recent:          make(map[string]time.Time),
		fallbackTimers:  make(map[string]*time.Timer),
		toolUseFallback: make(map[string]string),
	}
}

func (w *tuiPermissionWatcher) Feed(chunk []byte) {
	if w == nil || w.bridge == nil || len(chunk) == 0 {
		return
	}
	w.mu.Lock()
	// Prepend any tail held back from the previous read, then hold back this
	// read's own incomplete trailing escape / UTF-8 rune so stripANSI always
	// sees whole sequences. PTY reads split on 4096-byte boundaries; without
	// this an escape like "\x1b[5G" cut between reads would drop its ESC and
	// leak "5G" as literal text into the detection buffer (and a split CJK
	// byte would arrive as a replacement char). The held tail is bounded by
	// ansiCarryLimit, so it can't grow unboundedly.
	cleanRaw, tail := stripANSIChunk(w.pendingTail, chunk)
	w.pendingTail = tail
	clean := strings.ReplaceAll(cleanRaw, "\r", "\n")
	if strings.TrimSpace(clean) == "" {
		w.mu.Unlock()
		return
	}
	w.buffer += clean
	if len(w.buffer) > 20000 {
		w.buffer = w.buffer[len(w.buffer)-20000:]
	}
	prompt, ok := detectClaudeTUIApproval(w.buffer)
	waiting := false
	if !ok {
		waiting = w.bridge.claudeSessionWaitingForPermission()
		if waiting {
			prompt, ok = detectUnknownClaudeTUIApproval(w.buffer)
		}
	}
	// B5 drift watch: Claude reports it's waiting on a permission prompt (a
	// structured signal from ~/.claude/sessions/<pid>.json), yet neither the
	// structured nor the loosened-text detector recognized the frame — i.e. the
	// prompt copy drifted past even "Do you want to ". Emit ONE stderr line per
	// episode so the breakage is observable instead of silently swallowing the
	// web approval; reset once a prompt is recognized or the wait clears.
	switch {
	case ok || !waiting:
		w.driftReported = false
	case !w.driftReported:
		w.driftReported = true
		fmt.Fprintln(os.Stderr, "[pockly-wrapper] a permission prompt is awaiting but was not recognized — Claude Code's prompt copy may have changed; web approval is unavailable for this one (the wrapper detector needs updating).")
	}
	w.mu.Unlock()
	if ok {
		w.Start(prompt)
	}
}

func (w *tuiPermissionWatcher) Start(prompt tuiPermissionPrompt) {
	if w == nil || w.bridge == nil || prompt.Sig == "" {
		return
	}
	w.mu.Lock()
	if !w.startLocked(prompt) {
		w.mu.Unlock()
		return
	}
	w.mu.Unlock()
	go w.handle(prompt)
}

func (w *tuiPermissionWatcher) ObserveJSONLRecord(rec map[string]any) {
	if w == nil {
		return
	}
	for _, toolUseID := range detectClaudeToolResultIDs(rec) {
		w.CancelFallback(toolUseID)
	}
	if prompt, ok := detectClaudeFileToolApproval(rec); ok {
		w.ScheduleFallback(prompt)
		return
	}
	if prompt, ok := detectClaudeBashToolApproval(rec); ok {
		w.ScheduleFallback(prompt)
		return
	}
	if prompt, ok := detectClaudeGenericToolApproval(rec); ok {
		w.ScheduleFallback(prompt)
	}
}

func (w *tuiPermissionWatcher) ScheduleFallback(prompt tuiPermissionPrompt) {
	if w == nil || prompt.Sig == "" {
		return
	}
	w.mu.Lock()
	defer w.mu.Unlock()
	if !w.canStartLocked(prompt.Sig, time.Now()) {
		return
	}
	if existing := w.fallbackTimers[prompt.Sig]; existing != nil {
		return
	}
	if prompt.ToolUseID != "" {
		w.toolUseFallback[prompt.ToolUseID] = prompt.Sig
	}
	w.fallbackTimers[prompt.Sig] = time.AfterFunc(w.fallbackDelay, func() {
		w.StartScheduledFallback(prompt)
	})
}

func (w *tuiPermissionWatcher) StartScheduledFallback(prompt tuiPermissionPrompt) {
	if w == nil || prompt.Sig == "" {
		return
	}
	w.mu.Lock()
	if timer := w.fallbackTimers[prompt.Sig]; timer != nil {
		delete(w.fallbackTimers, prompt.Sig)
	}
	if prompt.ToolUseID != "" {
		delete(w.toolUseFallback, prompt.ToolUseID)
	}
	if w.bridge == nil || !w.bridge.claudeSessionWaitingForPermission() {
		w.mu.Unlock()
		return
	}
	if !w.startLocked(prompt) {
		w.mu.Unlock()
		return
	}
	w.mu.Unlock()
	go w.handle(prompt)
}

func (w *tuiPermissionWatcher) CancelFallback(toolUseID string) {
	if w == nil || toolUseID == "" {
		return
	}
	w.mu.Lock()
	defer w.mu.Unlock()
	sig := w.toolUseFallback[toolUseID]
	if sig == "" {
		return
	}
	delete(w.toolUseFallback, toolUseID)
	if timer := w.fallbackTimers[sig]; timer != nil {
		timer.Stop()
		delete(w.fallbackTimers, sig)
	}
}

func (w *tuiPermissionWatcher) startLocked(prompt tuiPermissionPrompt) bool {
	now := time.Now()
	if !w.canStartLocked(prompt.Sig, now) {
		return false
	}
	if timer := w.fallbackTimers[prompt.Sig]; timer != nil {
		timer.Stop()
		delete(w.fallbackTimers, prompt.Sig)
	}
	if prompt.ToolUseID != "" {
		delete(w.toolUseFallback, prompt.ToolUseID)
	}
	w.active[prompt.Sig] = struct{}{}
	// Clear the rendered-frame buffer after accepting a prompt so the same
	// stale TUI frame cannot retrigger as soon as the handler completes.
	w.buffer = ""
	return true
}

func (w *tuiPermissionWatcher) canStartLocked(sig string, now time.Time) bool {
	if _, ok := w.active[sig]; ok {
		return false
	}
	if until := w.recent[sig]; until.After(now) {
		return false
	}
	delete(w.recent, sig)
	return true
}

func (w *tuiPermissionWatcher) finish(prompt tuiPermissionPrompt) {
	w.mu.Lock()
	defer w.mu.Unlock()
	delete(w.active, prompt.Sig)
	w.recent[prompt.Sig] = time.Now().Add(w.recentTTL)
	if prompt.ToolUseID != "" {
		delete(w.toolUseFallback, prompt.ToolUseID)
	}
}

// tuiOptionRE matches a numbered option line in an ANSI-stripped approval
// frame: a single digit, a dot, whitespace, then the option text. The leading
// `(?:^|[^\d])` keeps it from latching onto a digit inside a version string.
var tuiOptionRE = regexp.MustCompile(`(?:^|[^\d])([1-9])\.[ \t]+(\S[^\r\n]*)`)

// parseTUIYesNoOptions scans an ANSI-stripped approval frame for the numbered
// option list and returns the keystroke numbers for the one-time "Yes" and the
// "No" choices. Replaces the old exact "1. Yes"/"3. No" substring check so a
// build that renumbers/reorders or lightly rewords the options still detects
// (and maps the keys correctly). The PERSISTENT yes ("Yes, and always allow…",
// "allow all edits…") is deliberately skipped — Pockly is a remote bridge and
// must select the one-time grant, never persist a rule. ok is false unless a
// one-time Yes AND a No are both found.
func parseTUIYesNoOptions(screen string) (allowKey, denyKey string, ok bool) {
	for _, m := range tuiOptionRE.FindAllStringSubmatch(screen, -1) {
		num := m[1]
		lower := strings.ToLower(strings.TrimSpace(m[2]))
		switch {
		case denyKey == "" && strings.HasPrefix(lower, "no"):
			denyKey = num
		case allowKey == "" && strings.HasPrefix(lower, "yes") &&
			!strings.Contains(lower, "always") &&
			!strings.Contains(lower, "allow all") &&
			!strings.Contains(lower, "don't ask") &&
			!strings.Contains(lower, "every time"):
			allowKey = num
		}
	}
	return allowKey, denyKey, allowKey != "" && denyKey != ""
}

func detectClaudeTUIApproval(screen string) (tuiPermissionPrompt, bool) {
	if !strings.Contains(screen, "Do you want to ") {
		return tuiPermissionPrompt{}, false
	}
	allowKey, denyKey, ok := parseTUIYesNoOptions(screen)
	if !ok {
		return tuiPermissionPrompt{}, false
	}
	promptLine := lastLineContaining(screen, "Do you want to ")
	if promptLine == "" {
		return tuiPermissionPrompt{}, false
	}
	toolName := "Claude tool"
	target := ""
	matches := tuiToolLineRE.FindAllStringSubmatch(screen, -1)
	if len(matches) > 0 {
		last := matches[len(matches)-1]
		toolName = strings.TrimSpace(last[1])
		if len(last) > 2 {
			target = strings.TrimSpace(last[2])
		}
	}
	if target == "" {
		target = extractApprovalTarget(promptLine)
	}
	input := map[string]any{
		"prompt": strings.TrimSpace(promptLine),
	}
	if strings.EqualFold(toolName, "Bash") {
		if command, description := extractTUIBashCommand(screen, target); command != "" {
			input["command"] = command
			if description != "" {
				input["description"] = description
			}
			target = command
		}
	}
	if target != "" {
		input["target"] = target
	}
	return tuiPermissionPrompt{
		ToolName: toolName,
		Input:    input,
		Sig:      permissionPromptSig(toolName, target, strings.TrimSpace(promptLine)),
		AllowKey: allowKey,
		DenyKey:  denyKey,
	}, true
}

func detectUnknownClaudeTUIApproval(screen string) (tuiPermissionPrompt, bool) {
	if !strings.Contains(screen, "Do you want to ") {
		return tuiPermissionPrompt{}, false
	}
	promptLine := lastLineContaining(screen, "Do you want to ")
	if promptLine == "" {
		promptLine = "Claude is waiting for confirmation in the local terminal."
	}
	return tuiPermissionPrompt{
		ToolName:  "Claude",
		Input:     map[string]any{"prompt": strings.TrimSpace(promptLine)},
		Sig:       permissionPromptSig("Claude", "", strings.TrimSpace(promptLine)),
		LocalOnly: true,
	}, true
}

func lastLineContaining(s, needle string) string {
	lines := strings.Split(s, "\n")
	for i := len(lines) - 1; i >= 0; i-- {
		if strings.Contains(lines[i], needle) {
			return strings.TrimSpace(lines[i])
		}
	}
	return ""
}

func extractApprovalTarget(line string) string {
	line = strings.TrimSpace(line)
	line = strings.TrimSuffix(line, "?")
	for _, prefix := range []string{
		"Do you want to create ",
		"Do you want to edit ",
		"Do you want to run ",
		"Do you want to ",
	} {
		if strings.HasPrefix(line, prefix) {
			return strings.TrimSpace(strings.TrimPrefix(line, prefix))
		}
	}
	return ""
}

func extractTUIBashCommand(screen, fallback string) (string, string) {
	lines := strings.Split(screen, "\n")
	for i, line := range lines {
		if strings.TrimSpace(line) != "Bash command" {
			continue
		}
		var values []string
		for _, raw := range lines[i+1:] {
			trimmed := strings.TrimSpace(raw)
			if trimmed == "" {
				if len(values) > 0 {
					break
				}
				continue
			}
			if strings.HasPrefix(trimmed, "Do you want to ") ||
				strings.HasPrefix(trimmed, "1. ") ||
				strings.HasPrefix(trimmed, "2. ") ||
				strings.HasPrefix(trimmed, "3. ") ||
				strings.HasPrefix(trimmed, "❯ ") ||
				strings.HasPrefix(trimmed, "Esc to ") {
				break
			}
			values = append(values, trimmed)
			if len(values) >= 2 {
				break
			}
		}
		if len(values) == 0 {
			return strings.TrimSpace(fallback), ""
		}
		description := ""
		if len(values) > 1 {
			description = values[1]
		}
		return values[0], description
	}
	return strings.TrimSpace(fallback), ""
}

